/** The Lucide icon name to show for a stored page or project icon (a Lucide name, an old emoji, or nothing). */
export function pageIconName(value, fallback = 'file-text') {
  const stored = typeof value === 'string' ? value.trim() : '';
  if (!stored) return fallback;
  if (hasIcon(stored)) return stored;
  const bare = stored.replace(/[︎️‍]/g, '');
  return EMOJI_ICONS[bare] || EMOJI_ICONS[Array.from(bare)[0]] || fallback;
}

/** SVG markup for a stored page or project icon. Projects pass `fallback: 'folder'`. */
export function pageIconSvg(value, { fallback = 'file-text', className = '' } = {}) {
  return iconSvg(pageIconName(value, fallback), `page-icon${className ? ` ${className}` : ''}`);
}
