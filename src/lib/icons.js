const FALLBACK_ICON = 'circle';

/** The Lucide shape for `name`, or a plain circle when the name is unknown. */
export function iconNode(name) {
  return ICONS[name] || ICONS[FALLBACK_ICON];
}

export function hasIcon(name) {
  return Object.prototype.hasOwnProperty.call(ICONS, name);
}

const escapeAttr = (value) => String(value).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');

/**
 * SVG markup for an icon, for code that builds HTML strings.
 * The icon is 1em square, so it follows the font size of its class, like the old icon font did.
 * `extra` is raw attribute text (for example `style="…"`); without an aria-label the icon is hidden from screen readers.
 */
export function iconSvg(name, className = '', extra = '') {
  const shape = iconNode(name)
    .map(([tag, attrs]) => `<${tag}${Object.entries(attrs).map(([key, value]) => ` ${key}="${escapeAttr(value)}"`).join('')}/>`)
    .join('');
  const labelled = /\baria-label=/.test(extra);
  const classes = `icon icon-${hasIcon(name) ? name : FALLBACK_ICON}${className ? ` ${className}` : ''}`;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="1em" height="1em" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" class="${escapeAttr(classes)}" ${labelled ? 'role="img"' : 'aria-hidden="true"'} focusable="false"${extra ? ` ${extra}` : ''}>${shape}</svg>`;
}

/** Changes an icon that is already on the page (an element made by iconSvg or <Icon>) to another one. */
export function setIcon(svg, name) {
  if (!svg) return;
  const known = hasIcon(name) ? name : FALLBACK_ICON;
  const holder = document.createElement('div');
  holder.innerHTML = iconSvg(known);
  svg.innerHTML = holder.firstChild.innerHTML;
  [...svg.classList].filter((item) => item.startsWith('icon-')).forEach((item) => svg.classList.remove(item));
  svg.classList.add(`icon-${known}`);
}

